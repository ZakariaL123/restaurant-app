export const localeTags = { en: 'en-GB', fr: 'fr-MA', ar: 'ar-MA' }
const language = ref<Language>('en')

function updateDocument() {
  document.documentElement.lang = language.value
  document.documentElement.dir = language.value === 'ar' ? 'rtl' : 'ltr'
}

if (typeof window !== 'undefined') {
  try {
    const saved = window.localStorage.getItem('restaurant-language')
    if (saved === 'en' || saved === 'fr' || saved === 'ar') language.value = saved
  } catch {
    /* The switcher still works if browser storage is disabled. */
  }
  updateDocument()
}

export function setLanguage(value: Language) {
  language.value = value
  if (typeof window === 'undefined') return
  updateDocument()
  try {
    window.localStorage.setItem('restaurant-language', value)
  } catch {
    /* optional */
  }
}

export function useLanguage() {
  return {
    language,
    setLanguage,
    t: (key: Key) => dictionary[language.value][key],
  }
}
